optimizer_gpt2 = AdamW(gpt2_model.parameters(), lr=3e-5)

epochs = 3

for epoch in range(epochs):
    print(f"Epoch {epoch+1} for T5-small")
    train_loss = train_epoch(t5_model, train_loader_t5, optimizer_t5, device)
    val_loss = evaluate(t5_model, val_loader_t5, device)
    print(f"T5 Train Loss: {train_loss:.4f} | Val Loss: {val_loss:.4f}")

    print(f"Epoch {epoch+1} for GPT-2 small")
    train_loss = train_epoch(gpt2_model, train_loader_gpt2, optimizer_gpt2, device)
    val_loss = evaluate(gpt2_model, val_loader_gpt2, device)
    print(f"GPT-2 Train Loss: {train_loss:.4f} | Val Loss: {val_loss:.4f}")

def generate_summary_t5(text, model, tokenizer, device, max_length=150):
    model.eval()
    inputs = tokenizer(text, return_tensors='pt', truncation=True, padding='max_length', max_length=512).to(device)
    summary_ids = model.generate(
        inputs['input_ids'],
        attention_mask=inputs['attention_mask'],
        max_length=max_length,
        num_beams=4,
        early_stopping=True
    )
    return tokenizer.decode(summary_ids[0], skip_special_tokens=True)

def generate_summary_gpt2(text, model, tokenizer, device, max_length=150):
    model.eval()
    input_ids = tokenizer.encode(text, return_tensors='pt').to(device)
    with torch.no_grad():
        outputs = model.generate(
            input_ids,
            max_length=max_length + input_ids.shape[-1],
            pad_token_id=tokenizer.eos_token_id,
            do_sample=True,
            top_k=50,
            top_p=0.95,
            num_return_sequences=1
        )
    # Remove input prompt from output to get summary
    generated_text = tokenizer.decode(outputs[0], skip_special_tokens=True)
    summary = generated_text[len(text):].strip()
    return summary

scorer = rouge_scorer.RougeScorer(['rouge1', 'rouge2', 'rougeL'], use_stemmer=True)

def evaluate_rouge(model, tokenizer, dataset, device, generate_func):
    model.eval()
    scores = {'rouge1': [], 'rouge2': [], 'rougeL': []}
    for idx in range(len(dataset)):
        article = dataset.data.iloc[idx]['Article']
        reference = dataset.data.iloc[idx]['Highlights']

        prediction = generate_func(article, model, tokenizer, device)
        rouge_scores = scorer.score(reference, prediction)
        for key in scores.keys():
            scores[key].append(rouge_scores[key].fmeasure)

    avg_scores = {key: sum(scores[key]) / len(scores[key]) for key in scores.keys()}
    return avg_scores

