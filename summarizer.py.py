train_df = pd.read_csv('train.csv')
val_df = pd.read_csv('validation.csv')
test_df = pd.read_csv('test.csv')

class SummarizationDataset(Dataset):
    def __init__(self, dataframe, tokenizer, model_type='t5', source_max_length=512, target_max_length=150):
        self.data = dataframe
        self.tokenizer = tokenizer
        self.model_type = model_type
        self.source_max_length = source_max_length
        self.target_max_length = target_max_length

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        article = str(self.data.iloc[idx]['article'])
        summary = str(self.data.iloc[idx]['highlights'])

        if self.model_type == 't5':
            source_encoding = self.tokenizer(article, max_length=self.source_max_length, padding='max_length', truncation=True, return_tensors="pt")
            target_encoding = self.tokenizer(summary, max_length=self.target_max_length, padding='max_length', truncation=True, return_tensors="pt")
            labels = target_encoding['input_ids']
            labels[labels == self.tokenizer.pad_token_id] = -100
            return {
                'input_ids': source_encoding['input_ids'].squeeze(),
                'attention_mask': source_encoding['attention_mask'].squeeze(),
                'labels': labels.squeeze()
            }
        elif self.model_type == 'gpt2':
            # GPT-2 doesn't have encoder, input + target concatenated (causal LM)
            input_encoding = self.tokenizer(article, max_length=self.source_max_length, truncation=True, return_tensors='pt')
            target_encoding = self.tokenizer(summary, max_length=self.target_max_length, truncation=True, return_tensors='pt')
            # For GPT2 fine-tuning, inputs are article + summary (for causal LM)
            input_ids = torch.cat([input_encoding['input_ids'], target_encoding['input_ids']], dim=1).squeeze()
            # labels equal to input_ids but ignore article tokens loss
            labels = input_ids.clone()
            labels[:input_encoding['input_ids'].size(1)] = -100  # Ignore article tokens loss
            return {
                'input_ids': input_ids,
                'attention_mask': torch.ones_like(input_ids),
                'labels': labels
            }

device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

# T5-small
t5_tokenizer = T5Tokenizer.from_pretrained('t5-small')
t5_model = T5ForConditionalGeneration.from_pretrained('t5-small').to(device)

# GPT-2 small
gpt2_tokenizer = GPT2Tokenizer.from_pretrained('gpt2')
gpt2_tokenizer.pad_token = gpt2_tokenizer.eos_token  # GPT2 has no pad token
gpt2_model = GPT2LMHeadModel.from_pretrained('gpt2').to(device)

train_dataset_t5 = SummarizationDataset(train_df, t5_tokenizer, model_type='t5')
val_dataset_t5 = SummarizationDataset(val_df, t5_tokenizer, model_type='t5')

train_dataset_gpt2 = SummarizationDataset(train_df, gpt2_tokenizer, model_type='gpt2')
val_dataset_gpt2 = SummarizationDataset(val_df, gpt2_tokenizer, model_type='gpt2')

train_loader_t5 = DataLoader(train_dataset_t5, batch_size=8, shuffle=True)
val_loader_t5 = DataLoader(val_dataset_t5, batch_size=8)

train_loader_gpt2 = DataLoader(train_dataset_gpt2, batch_size=2, shuffle=True)  # smaller batch for GPT2 due to memory
val_loader_gpt2 = DataLoader(val_dataset_gpt2, batch_size=2)

def train_epoch(model, dataloader, optimizer, device):
    model.train()
    total_loss = 0
    loop = tqdm(dataloader)
    for batch in loop:
        optimizer.zero_grad()
        input_ids = batch['input_ids'].to(device)
        attention_mask = batch['attention_mask'].to(device)
        labels = batch['labels'].to(device)

        outputs = model(input_ids=input_ids, attention_mask=attention_mask, labels=labels)
        loss = outputs.loss
        loss.backward()
        optimizer.step()

        total_loss += loss.item()
        loop.set_postfix(loss=loss.item())
    return total_loss / len(dataloader)

def evaluate(model, dataloader, device):
    model.eval()
    total_loss = 0
    with torch.no_grad():
        for batch in dataloader:
            input_ids = batch['input_ids'].to(device)
            attention_mask = batch['attention_mask'].to(device)
            labels = batch['labels'].to(device)

            outputs = model(input_ids=input_ids, attention_mask=attention_mask, labels=labels)
            loss = outputs.loss
            total_loss += loss.item()
    return total_loss / len(dataloader)

