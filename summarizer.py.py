import gradio as gr

def summarize(text, model_choice):
    if model_choice == "T5-small (Encoder-Decoder Transformer)":
        summary = generate_summary_t5(text, t5_model, t5_tokenizer, device)
    elif model_choice == "GPT-2 small (Decoder-only Transformer)":
        summary = generate_summary_gpt2(text, gpt2_model, gpt2_tokenizer, device)
    else:
        summary = "Invalid model choice."
    return summary

